# -- Acceso a la base de conocimiento en PostgreSQL.
# Es el único módulo que habla con la base

import logging
import math

import psycopg
from psycopg.rows import dict_row

import config

logger = logging.getLogger(__name__)


# Error con un mensaje para mostrar en pantalla: falta la dirección de la base o no se pudo conectar.
class ErrorBase(RuntimeError):
    pass


# Error de una regla de la base, por ejemplo una segunda ficha para el mismo #HA.
ErrorIntegridad = psycopg.IntegrityError


#-- Abre una conexión nueva a la base y la devuelve. Cada operación abre su propia conexión y la cierra
# al terminar. La base es PostgreSQL y vive fuera de la app, por eso no se usa un pool de conexiones.
def conectar():
    if not config.DB_URL:
        raise ErrorBase("Falta SGCT_DB_URL, la dirección de la base PostgreSQL. "
                        "Defínala en .streamlit/secrets.toml (en Streamlit Cloud, en los secrets).")
    try:
        conexion = psycopg.connect(
            config.DB_URL,
            # Cada sentencia se confirma sola; las que deben ir juntas se agrupan con
            # "with conexion.transaction():", que confirma al final o deshace todo si algo falla.
            autocommit=True,
            # Permite leer cada fila por nombre de columna (fila["causa"]) y no por posición.
            row_factory=dict_row,
            # El pooler de Supabase no admite sentencias preparadas.
            prepare_threshold=None,
            connect_timeout=config.DB_TIMEOUT_SEGUNDOS,
        )
    except psycopg.OperationalError as error:
        # El mensaje original puede traer el usuario y el servidor: va al log, no a la pantalla.
        logger.error("No se pudo conectar a PostgreSQL: %s", error)
        raise ErrorBase("No se pudo conectar a la base de datos. Revise SGCT_DB_URL y la conexión a internet.") from error

    # La URL lleva la contraseña: nunca va al log.
    logger.debug("Conexión abierta a PostgreSQL")
    return conexion


# La fecha se guarda como texto en UTC ("2026-10-28 19:24:27")
AHORA = "to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')"

# pandas marca las celdas vacías del Excel con NaN; PostgreSQL necesita None para guardarlas como NULL.
def _limpiar(valor):
    return None if isinstance(valor, float) and math.isnan(valor) else valor


# Las reglas van también en la base, si un módulo tiene un error,
# la base lo frena antes de que dañen los datos de la evaluación.

ESQUEMA = f"""
CREATE TABLE IF NOT EXISTS caso (
    ha                  TEXT PRIMARY KEY,
    tipo                TEXT,
    estado              TEXT,
    responsable         TEXT,
    id_flujo            TEXT,
    flujo               TEXT,
    descripcion         TEXT,
    observaciones       TEXT,
    causa_solucion      TEXT,
    categoria_excel     TEXT,
    subcategoria_excel  TEXT,
    sprint              TEXT,
    usuario_reporta     TEXT,
    fecha_recepcion     TEXT,
    fecha_cierre        TEXT,
    cargado_en          TEXT NOT NULL DEFAULT ({AHORA})
);

CREATE TABLE IF NOT EXISTS ficha (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ha                  TEXT NOT NULL UNIQUE REFERENCES caso(ha),
    sintoma             TEXT,
    causa               TEXT,
    solucion            TEXT,
    categoria           TEXT,
    subcategoria        TEXT,
    estado              TEXT NOT NULL DEFAULT 'borrador'
                        CHECK (estado IN ('borrador', 'final')),
    motor               TEXT NOT NULL,
    modelo              TEXT,
    marcas_sin_sustento INTEGER NOT NULL DEFAULT 0,
    duracion_ms         INTEGER,
    lecciones           TEXT,
    creada_en           TEXT NOT NULL DEFAULT ({AHORA}),
    actualizada_en      TEXT NOT NULL DEFAULT ({AHORA})
);

CREATE TABLE IF NOT EXISTS pregunta (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ficha_id            INTEGER NOT NULL REFERENCES ficha(id) ON DELETE CASCADE,
    orden               INTEGER NOT NULL,
    campo               TEXT NOT NULL,
    texto               TEXT NOT NULL,
    respuesta           TEXT,
    respondida_en       TEXT
);

CREATE TABLE IF NOT EXISTS evidencia (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ficha_id            INTEGER NOT NULL REFERENCES ficha(id) ON DELETE CASCADE,
    nombre              TEXT NOT NULL,
    tipo                TEXT NOT NULL,
    contenido           BYTEA NOT NULL,
    cargada_en          TEXT NOT NULL DEFAULT ({AHORA})
);
"""

# Crea las tablas que no existan. Se puede correr las veces que sea: no toca las que ya están.
def crear_tablas(conexion):
    with conexion.transaction():
        for sentencia in ESQUEMA.split(";"):
            if sentencia.strip():
                conexion.execute(sentencia)
    logger.info("Tablas de la base verificadas")

# Devuelve el conjunto de #HA que ya tienen ficha, sea borrador o final.
def ha_con_ficha(conexion):
    filas = conexion.execute("SELECT ha FROM ficha").fetchall()
    return {fila["ha"] for fila in filas}

# El id de la ficha de un caso, o None si todavía no tiene.
def id_ficha(conexion, ha):
    fila = conexion.execute("SELECT id FROM ficha WHERE ha = %s", (ha,)).fetchone()
    return fila["id"] if fila else None

# --- Escritura ---
# Estas funciones no abren su propia transacción: quien las llama (fichas.py) agrupa varias en una sola,
# para que nunca quede una ficha guardada sin sus preguntas.
COLUMNAS_CASO = ("ha", "tipo", "estado", "responsable", "id_flujo", "flujo", "descripcion",
                 "observaciones", "causa_solucion", "categoria_excel", "subcategoria_excel",
                 "sprint", "usuario_reporta", "fecha_recepcion", "fecha_cierre")

def _datos_caso(caso):
    return {c: _limpiar(caso.get(c)) for c in COLUMNAS_CASO}

# Guarda el caso tal como venía en el Excel, si ya existe, lo actualiza.
def guardar_caso(conexion, caso):
    columnas = ", ".join(COLUMNAS_CASO)
    valores = ", ".join(f"%({c})s" for c in COLUMNAS_CASO)
    actualizar = ", ".join(f"{c} = excluded.{c}" for c in COLUMNAS_CASO if c != "ha")
    conexion.execute(
        f"INSERT INTO caso ({columnas}) VALUES ({valores}) "
        f"ON CONFLICT (ha) DO UPDATE SET {actualizar}, cargado_en = {AHORA}",
        _datos_caso(caso),
    )

# Actualiza, con los datos del Excel recién cargado, los casos que ya están en la base (los que tienen ficha).
def actualizar_casos(conexion, casos):
    asignaciones = ", ".join(f"{c} = %({c})s" for c in COLUMNAS_CASO if c != "ha")
    with conexion.cursor() as cursor:
        cursor.executemany(
            f"UPDATE caso SET {asignaciones}, cargado_en = {AHORA} WHERE ha = %(ha)s",
            [_datos_caso(fila) for _, fila in casos.iterrows()],
        )

# Crea la ficha y devuelve su id.
def insertar_ficha(conexion, ficha):
    return conexion.execute(
        "INSERT INTO ficha (ha, sintoma, causa, solucion, categoria, subcategoria, estado, "
        "motor, modelo, marcas_sin_sustento, duracion_ms) "
        "VALUES (%(ha)s, %(sintoma)s, %(causa)s, %(solucion)s, %(categoria)s, %(subcategoria)s, %(estado)s, "
        "%(motor)s, %(modelo)s, %(marcas_sin_sustento)s, %(duracion_ms)s) RETURNING id",
        ficha,
    ).fetchone()["id"]

# Guarda las preguntas de una ficha en el orden en que se hicieron.
def insertar_preguntas(conexion, ficha_id, preguntas):
    with conexion.cursor() as cursor:
        cursor.executemany(
            "INSERT INTO pregunta (ficha_id, orden, campo, texto) VALUES (%s, %s, %s, %s)",
            [(ficha_id, orden, p["campo"], p["texto"]) for orden, p in enumerate(preguntas, start=1)],
        )

# Registra la respuesta a una pregunta y cuándo se respondió.
def responder_pregunta(conexion, pregunta_id, respuesta):
    conexion.execute(
        f"UPDATE pregunta SET respuesta = %s, respondida_en = {AHORA} WHERE id = %s",
        (respuesta, pregunta_id),
    )

# Actualiza los campos de la ficha que vengan en "campos" y su estado.
def actualizar_ficha(conexion, ficha_id, campos, estado):
    permitidos = ("sintoma", "causa", "solucion", "categoria", "subcategoria", "lecciones")
    asignaciones = "".join(f"{c} = %({c})s, " for c in campos if c in permitidos)
    conexion.execute(
        f"UPDATE ficha SET {asignaciones}estado = %(estado)s, actualizada_en = {AHORA} WHERE id = %(id)s",
        {**{c: v for c, v in campos.items() if c in permitidos}, "estado": estado, "id": ficha_id},
    )

# --- Lectura ---
# Una ficha con los datos de su caso, o None si no existe.
def obtener_ficha(conexion, ficha_id):
    return conexion.execute(
        "SELECT f.*, c.tipo, c.responsable, c.id_flujo, c.flujo, c.descripcion, c.observaciones, c.causa_solucion, "
        "       c.sprint, c.usuario_reporta, c.fecha_recepcion, c.fecha_cierre "
        "FROM ficha f JOIN caso c ON c.ha = f.ha WHERE f.id = %s",
        (ficha_id,),
    ).fetchone()

# Las preguntas de una ficha en orden.
def obtener_preguntas(conexion, ficha_id):
    return conexion.execute(
        "SELECT * FROM pregunta WHERE ficha_id = %s ORDER BY orden", (ficha_id,)
    ).fetchall()

# Todas las fichas con lo necesario para la lista de consulta, la más reciente primero.
def listar_fichas(conexion):
    return conexion.execute(
        "SELECT f.id, f.ha, c.tipo, c.responsable, c.id_flujo, c.flujo, c.sprint, c.descripcion, "
        "       f.sintoma, f.causa, f.solucion, f.categoria, f.subcategoria, f.lecciones, "
        "       f.estado, f.motor, f.marcas_sin_sustento, f.creada_en, f.actualizada_en, "
        "       COUNT(p.id) AS preguntas, "
        "       COUNT(p.id) - COUNT(p.respuesta) AS sin_responder "
        "FROM ficha f JOIN caso c ON c.ha = f.ha LEFT JOIN pregunta p ON p.ficha_id = f.id "
        "GROUP BY f.id, c.ha ORDER BY f.actualizada_en DESC, f.id DESC"
    ).fetchall()

# --- Evidencias ---
# Guarda una imagen adjunta a la ficha.
def insertar_evidencia(conexion, ficha_id, nombre, tipo, contenido):
    conexion.execute(
        "INSERT INTO evidencia (ficha_id, nombre, tipo, contenido) VALUES (%s, %s, %s, %s)",
        (ficha_id, nombre, tipo, contenido),
    )

# Las imágenes de una ficha, en el orden en que se cargaron.
def obtener_evidencias(conexion, ficha_id):
    return conexion.execute(
        "SELECT id, nombre, tipo, contenido FROM evidencia WHERE ficha_id = %s ORDER BY id", (ficha_id,)
    ).fetchall()

# Quita una imagen de una ficha.
def borrar_evidencia(conexion, evidencia_id):
    conexion.execute("DELETE FROM evidencia WHERE id = %s", (evidencia_id,))
